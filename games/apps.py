def seed(sender, **kwargs):
    from .models import Game
    for slug, title, emoji, desc, genre in GAMES:
        g, _ = Game.objects.get_or_create(slug=slug, defaults=dict(title=title, emoji=emoji, description=desc, genre=genre))
        if (g.genre, g.title, g.description) != (genre, title, desc):
            g.genre, g.title, g.description = genre, title, desc; g.save()

class GamesConfig(AppConfig):
    name = "games"
    def ready(self):
        post_migrate.connect(seed, sender=self)
